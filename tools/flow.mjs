// UI flow test: title -> select -> fight -> pause -> movelist -> resume
import {chromium} from 'playwright';
import http from 'http'; import fs from 'fs'; import path from 'path';
const root=process.env.GAME_ROOT||decodeURIComponent(new URL('..', import.meta.url).pathname).replace(/\/$/, '');
const types={'.html':'text/html','.js':'text/javascript','.json':'application/json','.png':'image/png','.jpg':'image/jpeg','.bin':'application/octet-stream','.ttf':'font/ttf'};
const srv=http.createServer((q,r)=>{const p=path.join(root,decodeURIComponent(q.url.split('?')[0]));fs.readFile(p,(e,d)=>{if(e){r.writeHead(404);return r.end();}r.writeHead(200,{'Content-Type':types[path.extname(p)]||'application/octet-stream'});r.end(d);});}).listen(0,'127.0.0.1');
await new Promise(r=>srv.on('listening',r)); const PORT=srv.address().port;
const b=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const p=await b.newPage({viewport:{width:960,height:540}});
p.on('pageerror',e=>console.log('PAGEERROR',e.message));
p.on('console',m=>{ if(m.type()==='error' && !m.text().includes('404')) console.log('console.error', m.text()); });
await p.goto(`http://127.0.0.1:${PORT}/index.html?q=low&nodynres=1`);
const st = async () => JSON.parse(await p.evaluate(() => window.__debug ? window.__debug() : '{}'));
const waitState = async (s, to=240000) => { const t0=Date.now(); while(Date.now()-t0<to){ const d=await st(); if(d.state===s) return d; await p.waitForTimeout(1000);} throw new Error('timeout waiting '+s+' last='+JSON.stringify(await st())); };
const key = async (k) => { await p.keyboard.down(k); await p.waitForTimeout(250); await p.keyboard.up(k); await p.waitForTimeout(700); };
let d = await waitState('title'); console.log('1 title ok', d.screens);
await key('Enter'); d = await waitState('select'); console.log('2 select ok', d.screens);
await key('KeyD'); await key('KeyD'); await key('KeyU');
d = await waitState('fight'); console.log('3 fight started', d.phase, d.f && d.f.map(x=>x.id));
await p.waitForTimeout(8000);
await key('Escape'); d = await waitState('pause'); console.log('4 paused', d.screens);
await key('ArrowDown'); await key('Enter'); await p.waitForTimeout(1500); d = await st(); console.log('5 movelist state', d.state, d.screens);
const rows = await p.evaluate(() => document.querySelectorAll('#overlay table tr').length); console.log('   movelist rows', rows);
await key('Escape'); await p.waitForTimeout(1000); d = await st(); console.log('6 back', d.state);
await key('Enter'); await p.waitForTimeout(1500); d = await st(); console.log('7 resumed', d.state, d.phase);
await b.close(); srv.close();
